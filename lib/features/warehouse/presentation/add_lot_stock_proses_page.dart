class AddLotStockProsesPage extends ConsumerStatefulWidget {
  final List<BuahRawItem> selectedBuahRaw;

  const AddLotStockProsesPage({
    super.key,
    required this.selectedBuahRaw,
  });

  @override
  ConsumerState<AddLotStockProsesPage> createState() =>
      _AddLotStockProsesPageState();
}

class _AddLotStockProsesPageState extends ConsumerState<AddLotStockProsesPage> {
  bool _isLotBaru = true;

  String? _selectedKondisi;
  String _autoGeneratedJenis = '';
  String _autoGeneratedJenisId = '';
  String? _kondisiError;

  String? _selectedLotExisting;
  String? _lotExistingError;

  final List<Map<String, String>> _kondisiOptions = [
    {'value': 'A', 'label': 'A - Bagus'},
    {'value': 'B', 'label': 'B - Rusak Sebagian / Bakal Pulping'},
    {'value': 'M', 'label': 'M - Belum Masak'},
    {'value': 'R', 'label': 'R - Reject / Rusak / Busuk'},
  ];

  bool _isSubmitting = false;
  bool _isSubmitted = false;
  String _createdLotId = '';
  String _createdLotKode = '';

  @override
  void initState() {
    super.initState();
    _initJenis();
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _initDraftLotsFilter();
    });
  }

  void _initJenis() {
    final firstBuah = widget.selectedBuahRaw.first;
    _autoGeneratedJenis = firstBuah.jenisDurian.kode;
    _autoGeneratedJenisId = firstBuah.jenisDurian.id;
  }

  void _initDraftLotsFilter() {
    ref.read(draftLotsParamsProvider.notifier).setJenisDurianId(_autoGeneratedJenisId);
  }

  Future<void> _submitLot() async {
    _kondisiError = null;
    _lotExistingError = null;

    if (_isLotBaru) {
      if (_selectedKondisi == null) {
        setState(() {
          _kondisiError = 'Pilih kondisi buah';
        });
        return;
      }
    } else {
      if (_selectedLotExisting == null) {
        setState(() {
          _lotExistingError = 'Pilih lot tujuan';
        });
        return;
      }

      final draftLotsAsync = ref.read(draftLotsProvider);
      final draftLots = draftLotsAsync.value?.data ?? [];
      final selectedLot = draftLots.firstWhere(
        (lot) => lot.id == _selectedLotExisting,
      );

      if (selectedLot.jenisDurianNama != _autoGeneratedJenis) {
        _showJenisWarning(selectedLot.jenisDurianNama);
        return;
      }
    }

    setState(() {
      _isSubmitting = true;
    });

    try {
      final buahRawIds = widget.selectedBuahRaw.map((b) => b.id).toList();
      String lotId;

      if (_isLotBaru) {
        final createRequest = CreateLotRequest(
          jenisDurianId: _autoGeneratedJenisId,
          kondisiBuah: _selectedKondisi!,
        );

        final createResult = await ref
            .read(createLotControllerProvider.notifier)
            .createLot(createRequest);

        if (createResult == null) {
          _showErrorSnackbar('Gagal membuat lot baru');
          setState(() {
            _isSubmitting = false;
          });
          return;
        }

        lotId = createResult.id;
        _createdLotKode = createResult.kode;
      } else {
        lotId = _selectedLotExisting!;
        final draftLotsAsync = ref.read(draftLotsProvider);
        final draftLots = draftLotsAsync.value?.data ?? [];
        final selectedLot = draftLots.firstWhere((lot) => lot.id == lotId);
        _createdLotKode = selectedLot.kode;
      }

      final addItemsRequest = AddItemsToLotRequest(buahRawIds: buahRawIds);
      final addItemsResult = await ref
          .read(addItemsToLotControllerProvider.notifier)
          .addItems(lotId, addItemsRequest);

      if (addItemsResult == null) {
        _showErrorSnackbar('Gagal menambahkan buah ke lot');
        setState(() {
          _isSubmitting = false;
        });
        return;
      }

      setState(() {
        _createdLotId = lotId;
        _isSubmitted = true;
        _isSubmitting = false;
      });

      ref.invalidate(draftLotsProvider);

      _showSuccessSnackbar(
        _isLotBaru
            ? 'Lot baru $_createdLotKode berhasil dibuat dengan ${widget.selectedBuahRaw.length} buah'
            : '${widget.selectedBuahRaw.length} buah berhasil ditambahkan ke $_createdLotKode',
      );
    } catch (e) {
      setState(() {
        _isSubmitting = false;
      });
      _showErrorSnackbar('Terjadi kesalahan: $e');
    }
  }

